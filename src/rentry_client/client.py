"""Client for the rentry.co API.

The /api endpoints are CSRF-exempt: no csrf token, cookies or Referer header
are needed. Every method returns the parsed JSON response as a dict with at
least 'status' and 'content' keys ('status' is '200' on success).

After 3 wrong edit codes on a page within an hour, that page's edit, fetch and
delete refuse requests without a captcha code, returning status '429' with a
'captcha_url' key. A person gets a code by solving the captcha at captcha_url
in a browser. Pass it as captcha_code to RentryClient (or per call) and keep it
alive with extend_captcha_code().
"""

import json
import urllib.parse
import urllib.request


class RentryClient:
    """Thin client for the rentry.co API. Works against any rentry instance via base_url."""

    def __init__(self, base_url='https://rentry.co', captcha_code=None):
        """captcha_code, if given, is sent with every edit, fetch and delete.

        It is ignored by pages that are not gated, so it is safe to always set.
        """
        self.base_url = base_url.rstrip('/')
        self.captcha_code = captcha_code

    def new(self, text, url=None, edit_code=None, metadata=None):
        """Create a new page. url and edit_code are generated by the server if not given.

        metadata may be a newline-separated string ('OPTION = value') or a dict.
        """
        payload = {'text': text}
        if url is not None:
            payload['url'] = url
        if edit_code is not None:
            payload['edit_code'] = edit_code
        if metadata is not None:
            payload['metadata'] = self._encode_metadata(metadata)
        return self._post('/api/new', payload)

    def edit(self, url, edit_code, text=None, metadata=None, update_mode=None,
             update_secret_metadata=None, new_url=None, new_edit_code=None,
             new_modify_code=None, captcha_code=None):
        """Edit an existing page. edit_code may also be a modify code ('m:...').

        update_mode: 'upsert' changes only the metadata options provided and keeps
            the rest; default is a full replacement of text and metadata.
        update_secret_metadata: previously-set SECRET_* metadata is preserved by
            default no matter what the edit sends. Pass True to allow this edit to
            change or remove it.
        new_modify_code: provide 'm:' to unset an existing modify code.
        captcha_code: overrides the client's captcha_code for this request.
        """
        payload = {'edit_code': edit_code}
        if text is not None:
            payload['text'] = text
        if metadata is not None:
            payload['metadata'] = self._encode_metadata(metadata)
        if update_mode is not None:
            payload['update_mode'] = update_mode
        if update_secret_metadata is not None:
            payload['update_secret_metadata'] = 'true' if update_secret_metadata else 'false'
        if new_url is not None:
            payload['new_url'] = new_url
        if new_edit_code is not None:
            payload['new_edit_code'] = new_edit_code
        if new_modify_code is not None:
            payload['new_modify_code'] = new_modify_code
        self._add_captcha_code(payload, captcha_code)
        return self._post('/api/edit/{}'.format(url), payload)

    def fetch(self, url, edit_code, captcha_code=None):
        """Fetch a page's full details (text, metadata, views, dates...)."""
        payload = {'edit_code': edit_code}
        self._add_captcha_code(payload, captcha_code)
        return self._post('/api/fetch/{}'.format(url), payload)

    def delete(self, url, edit_code, captcha_code=None):
        """Delete a page. Requires the edit code (not a modify code)."""
        payload = {'edit_code': edit_code}
        self._add_captcha_code(payload, captcha_code)
        return self._post('/api/delete/{}'.format(url), payload)

    def extend_captcha_code(self, captcha_code=None):
        """Record use of a captcha code so it does not expire, without editing anything.

        A code expires after 90 days unused, and sending it to a page that is not
        gated does not count as use. On success the response has 'expires', the
        last UTC date (YYYY-MM-DD) the code works if nothing uses it again.
        Defaults to the client's captcha_code. Status '404' means the code is
        unknown, expired or used up, and a new one is needed from 'captcha_url'.

        On an instance without captcha codes the endpoint does not exist, and
        this raises urllib.error.HTTPError (404), as other methods do for HTTP errors.
        """
        if captcha_code is None:
            captcha_code = self.captcha_code
        return self._post('/api/extend-captcha-code', {'captcha_code': captcha_code or ''})

    def raw(self, url, auth_code=None):
        """Get a page's raw markdown text.

        auth_code is a rentry-auth access code (from support@rentry.co), or the
        page's own SECRET_RAW_ACCESS_CODE value.
        """
        headers = {'rentry-auth': auth_code} if auth_code is not None else {}
        return self._get('/api/raw/{}'.format(url), headers)

    def _add_captcha_code(self, payload, captcha_code):
        if captcha_code is None:
            captcha_code = self.captcha_code
        if captcha_code:
            payload['captcha_code'] = captcha_code

    @staticmethod
    def _encode_metadata(metadata):
        if isinstance(metadata, dict):
            return json.dumps(metadata)
        return metadata

    def _post(self, path, payload):
        data = urllib.parse.urlencode(payload).encode()
        request = urllib.request.Request(self.base_url + path, data)
        return self._request(request)

    def _get(self, path, headers={}):
        request = urllib.request.Request(self.base_url + path, headers=headers)
        return self._request(request)

    @staticmethod
    def _request(request):
        with urllib.request.urlopen(request) as response:
            return json.loads(response.read().decode('utf-8'))
